# -*- coding: utf-8 -*-
"""Table-driven I/O setup for a CODESYS project: CSV in, import files out, plus a checker.

  python -I make_io.py io_table.csv --out build [options]      generate
  python -I make_io.py --check build --export <export folder>  check a built project's export

Generate writes into --out:
  build_config.json   what cds_apply.py does (modules, channel mappings, GVL, POUs, task calls)
  <GVL>.st            one global variable list for every tag with a global_tag
  <InPOU>.xml         LD program: DI contact -> global coil; AI MOVE card word -> global   (PLCopen XML)
  <OutPOU>.xml        LD program: global contact -> DO card coil; global MOVE -> AO card    (only if any)
  IO_List.md          readable I/O list from the same table

CSV columns (header row required; one row per channel; module columns repeat on each row):
  slot, module_name, dev_type, dev_id, dev_version, module_id,     module: name in the tree + device ids
  kind, channel, param,                                            DI | DO | AI | AO, channel number, parameter
                                                                   name (blank = default pattern per kind)
  card_tag, global_tag, data_type,                                 card-level variable; global tag (blank = none);
                                                                   data type of AI/AO globals (blank = WORD)
  device, description, drawing                                     comments: device tag, text, drawing ref
Module ids come from the installed device description (rules/21 §4). Rows are applied in file order;
modules are created in order of first appearance.
"""
import argparse
import csv
import json
import os
import re
import sys
from xml.sax.saxutils import escape

DEFAULT_PARAM = {"DI": "Input value Ch{ch}", "AI": "Input value Ch{ch}",
                 "DO": "Output value Ch{ch}", "AO": "Output value Ch{ch}"}
LEFT, RIGHT = 0, 2147483646


# ---------- table ----------
def load(csv_path):
    with open(csv_path, newline="", encoding="utf-8-sig") as f:
        rows = [{k.strip(): (v or "").strip() for k, v in r.items()} for r in csv.DictReader(f)]
    need = ["slot", "module_name", "dev_type", "dev_id", "dev_version", "module_id", "kind", "channel", "card_tag"]
    errs = []
    for i, r in enumerate(rows, 2):
        for c in need:
            if not r.get(c):
                errs.append("row %d: %s is empty" % (i, c))
        if r.get("kind") not in DEFAULT_PARAM:
            errs.append("row %d: kind must be DI/DO/AI/AO, not %r" % (i, r.get("kind")))
    names = [r["card_tag"] for r in rows] + [r["global_tag"] for r in rows if r.get("global_tag")]
    dup = sorted(set(n for n in names if names.count(n) > 1))
    if dup:
        errs.append("duplicate tag names: %s" % ", ".join(dup))
    if errs:
        sys.exit("io table errors:\n  " + "\n  ".join(errs))
    return rows


def modules(rows):
    out, seen = [], {}
    for r in rows:
        n = r["module_name"]
        if n not in seen:
            seen[n] = dict(slot=r["slot"], name=n, dev_type=int(r["dev_type"]), dev_id=r["dev_id"],
                           dev_version=r["dev_version"], module_id=r["module_id"], channels=[])
            out.append(seen[n])
        seen[n]["channels"].append(dict(
            param=r.get("param") or DEFAULT_PARAM[r["kind"]].format(ch=int(r["channel"])),
            var=r["card_tag"], comment=" ".join(x for x in (r.get("device"), r.get("description")) if x)))
    return out


def comment(r):
    bits = [" ".join(x for x in (r.get("device"), r.get("description")) if x),
            "slot %s %s ch%s" % (r["slot"], r["module_name"], r["channel"]), r.get("drawing", "")]
    return " | ".join(b for b in bits if b)


def gtype(r):
    return "BOOL" if r["kind"] in ("DI", "DO") else (r.get("data_type") or "WORD")


# ---------- generated text ----------
def gvl_text(rows, gvl):
    lines = ["{attribute 'qualified_only'}",
             "// %s: generated by make_io.py from the I/O table. Edit the table, not this list." % gvl,
             "VAR_GLOBAL"]
    last = None
    for r in rows:
        if not r.get("global_tag"):
            continue
        if r["module_name"] != last:
            lines += ["", "\t// ---- slot %s: %s" % (r["slot"], r["module_name"])]
            last = r["module_name"]
        lines.append("\t%s : %s; // %s" % (r["global_tag"], gtype(r), comment(r)))
    return "\n".join(lines + ["END_VAR", ""])


def _title(i, text):
    return ('<comment localId="%d" height="0" width="0"><position x="0" y="0" /><content><xhtml xmlns="http://www.w3.org/1999/xhtml">%s</xhtml></content></comment>\n'
            '<vendorElement localId="%d"><position x="0" y="0" /><alternativeText><xhtml xmlns="http://www.w3.org/1999/xhtml" /></alternativeText><addData><data name="http://www.3s-software.com/plcopenxml/fbdelementtype" handleUnknown="implementation"><ElementType xmlns="">networktitle</ElementType></data></addData></vendorElement>\n'
            % (i, escape(text), i + 1))


def rung_coil(i, src, dst, text):
    return _title(i, text) + (
        '<contact localId="%d" negated="false" storage="none" edge="none"><position x="0" y="0" /><connectionPointIn><connection refLocalId="%d" /></connectionPointIn><connectionPointOut /><variable>%s</variable></contact>\n'
        '<coil localId="%d" negated="false" storage="none"><position x="0" y="0" /><connectionPointIn><connection refLocalId="%d" /></connectionPointIn><connectionPointOut /><variable>%s</variable></coil>\n'
        % (i + 2, LEFT, escape(src), i + 3, i + 2, escape(dst)))


def rung_move(i, src, dst, text):
    # MOVE needs EN in, ENO out and the destination as an expression on Out1 (rules/21 §5).
    return _title(i, text) + (
        '<inVariable localId="%d"><position x="0" y="0" /><connectionPointOut /><expression>%s</expression></inVariable>\n'
        '<block localId="%d" typeName="MOVE"><position x="0" y="0" />'
        '<inputVariables><variable formalParameter="EN"><connectionPointIn><connection refLocalId="%d" /></connectionPointIn></variable>'
        '<variable formalParameter="In2"><connectionPointIn><connection refLocalId="%d" /></connectionPointIn></variable></inputVariables>'
        '<inOutVariables /><outputVariables><variable formalParameter="ENO"><connectionPointOut /></variable>'
        '<variable formalParameter="Out1"><connectionPointOut><expression>%s</expression></connectionPointOut></variable></outputVariables>'
        '<addData><data name="http://www.3s-software.com/plcopenxml/fbdcalltype" handleUnknown="implementation"><CallType xmlns="">operator</CallType></data></addData></block>\n'
        % (i + 3, escape(src), i + 2, LEFT, i + 3, escape(dst)))


def networks(rows, gvl, direction):
    """[(src, dst, is_bool, comment)] for one POU. direction 'in': card -> global; 'out': global -> card."""
    kinds = ("DI", "AI") if direction == "in" else ("DO", "AO")
    out = []
    for r in rows:
        if r["kind"] in kinds and r.get("global_tag"):
            g = "%s.%s" % (gvl, r["global_tag"])
            src, dst = (r["card_tag"], g) if direction == "in" else (g, r["card_tag"])
            out.append((src, dst, r["kind"] in ("DI", "DO"), comment(r)))
    return out


def pou_xml(name, nets):
    body = ['<leftPowerRail localId="%d"><position x="0" y="0" /><connectionPointOut formalParameter="none" /></leftPowerRail>\n' % LEFT]
    for n, (src, dst, is_bool, text) in enumerate(nets):
        body.append((rung_coil if is_bool else rung_move)(1 + 10 * n, src, dst, text))
    body.append('<rightPowerRail localId="%d"><position x="0" y="0" /><connectionPointIn /></rightPowerRail>\n' % RIGHT)
    return ('<?xml version="1.0" encoding="utf-8"?>\n<project xmlns="http://www.plcopen.org/xml/tc6_0200">\n'
            '<fileHeader companyName="" productName="CODESYS" productVersion="CODESYS V3.5" creationDateTime="2000-01-01T00:00:00" />\n'
            '<contentHeader name="%s"><coordinateInfo><fbd><scaling x="1" y="1" /></fbd><ld><scaling x="1" y="1" /></ld><sfc><scaling x="1" y="1" /></sfc></coordinateInfo></contentHeader>\n'
            '<types><dataTypes /><pous>\n<pou name="%s" pouType="program">\n<interface />\n<body><LD>\n%s</LD></body>\n<addData />\n</pou>\n</pous></types>\n'
            '<instances><configurations /></instances>\n</project>\n') % (escape(name), escape(name), "".join(body))


def io_list_md(rows, gvl, src_name):
    out = ["# I/O list", "", "Generated by make_io.py from `%s`. Do not edit; change the table and rebuild." % src_name, "",
           "| Slot | Module | Ch | Kind | Card-level tag | Global tag | Device | Description | Drawing |",
           "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        g = "`%s.%s`" % (gvl, r["global_tag"]) if r.get("global_tag") else "—"
        out.append("| %s | %s | %s | %s | `%s` | %s | %s | %s | %s |" % (
            r["slot"], r["module_name"], r["channel"], r["kind"], r["card_tag"], g,
            r.get("device") or "—", r.get("description", ""), r.get("drawing", "")))
    return "\n".join(out) + "\n"


def generate(a):
    rows = load(a.table)
    os.makedirs(a.out, exist_ok=True)
    nets_in, nets_out = networks(rows, a.gvl, "in"), networks(rows, a.gvl, "out")
    pous = [dict(name=a.in_pou, file=a.in_pou + ".xml", networks=[[s, d] for s, d, _, _ in nets_in])]
    if nets_out:
        pous.append(dict(name=a.out_pou, file=a.out_pou + ".xml", networks=[[s, d] for s, d, _, _ in nets_out]))
    for p, nets in zip(pous, (nets_in, nets_out)):
        with open(os.path.join(a.out, p["file"]), "w", encoding="utf-8") as f:
            f.write(pou_xml(p["name"], nets))
    with open(os.path.join(a.out, a.gvl + ".st"), "w", encoding="utf-8") as f:
        f.write(gvl_text(rows, a.gvl))
    with open(os.path.join(a.out, "IO_List.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write(io_list_md(rows, a.gvl, os.path.basename(a.table)))
    cfg = dict(io_parent=a.io_parent, rebuild_modules=not a.keep_modules, modules=modules(rows),
               remove_objects=[x for x in a.remove.split(",") if x],
               gvl=dict(name=a.gvl, file=a.gvl + ".st",
                        vars=[r["global_tag"] for r in rows if r.get("global_tag")]),
               pous=pous, task=a.task)
    with open(os.path.join(a.out, "build_config.json"), "w", encoding="utf-8") as f:
        json.dump(cfg, f, indent=1)
    print("make_io: %d modules, %d channels, %d global tags, %s" % (
        len(cfg["modules"]), len(rows), len(cfg["gvl"]["vars"]),
        ", ".join("%s %d networks" % (p["name"], len(p["networks"])) for p in pous)))


# ---------- check ----------
def check(build_dir, export_dir):
    cfg = json.load(open(os.path.join(build_dir, "build_config.json"), encoding="utf-8"))
    x = open(os.path.join(export_dir, "project_plcopen.xml"), encoding="utf-8").read()
    bad = []
    names = [m["name"] for m in cfg["modules"]]
    # module order as listed in the export under the I/O parent (rules/21 §4: not get_children())
    s = x.find('<configuration name="%s"' % cfg["io_parent"])
    if s < 0:
        bad.append("I/O parent %s not in export" % cfg["io_parent"])
    else:
        found = [n for n in re.findall(r'<configuration name="([^"]+)"', x[s + 1:]) if n in names]
        if cfg["rebuild_modules"] and found != names:
            bad.append("module order %s" % found)
    for m in cfg["modules"]:
        s = x.find('<configuration name="%s"' % m["name"])
        if s < 0:
            bad.append("module %s missing" % m["name"]); continue
        maps = re.findall(r"<Mapping>([^<]+)</Mapping>", x[s:x.find("</configuration>", s)])
        for ch in m["channels"]:
            if ch["var"] not in maps:
                bad.append("%s: %s not mapped" % (m["name"], ch["var"]))
    for p in cfg["pous"]:
        s = x.find('<pou name="%s"' % p["name"])
        if s < 0:
            bad.append("POU %s missing" % p["name"]); continue
        body = x[s:x.find("</pou>", s)]
        if body.count("networktitle") != len(p["networks"]):
            bad.append("%s: %d networks, expected %d" % (p["name"], body.count("networktitle"), len(p["networks"])))
        got = re.findall(r"<(?:variable|expression)>([^<]+)</(?:variable|expression)>", body)
        want = [v for pair in p["networks"] for v in pair]
        if got != want:
            bad.append("%s: rung variables differ from the table" % p["name"])
        t = x.find('<task name="%s"' % cfg["task"])
        if t < 0 or ('pouInstance name="%s"' % p["name"]) not in x[t:x.find("</task>", t)]:
            bad.append("%s not called by task %s" % (p["name"], cfg["task"]))
    s = x.find('<globalVars name="%s"' % cfg["gvl"]["name"])
    gv = re.findall(r'<variable name="([^"]+)"', x[s:x.find("</globalVars>", s)]) if s >= 0 else []
    if gv != cfg["gvl"]["vars"]:
        bad.append("%s variables differ from the table" % cfg["gvl"]["name"])
    return bad


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("table", nargs="?", help="I/O table CSV")
    ap.add_argument("--out", default="build", help="output folder (default build)")
    ap.add_argument("--io-parent", default="Local_IO", help="device the I/O modules sit under")
    ap.add_argument("--gvl", default="Global_Tags", help="global variable list name")
    ap.add_argument("--in-pou", default="ScanInputs", help="input scan POU name")
    ap.add_argument("--out-pou", default="ScanOutputs", help="output scan POU name")
    ap.add_argument("--task", default="MAIN_TASK", help="task that calls the POUs")
    ap.add_argument("--remove", default="", help="comma list of application objects to delete first")
    ap.add_argument("--keep-modules", action="store_true", help="map channels on existing modules instead of recreating them")
    ap.add_argument("--check", metavar="BUILD_DIR", help="check mode: build folder with build_config.json")
    ap.add_argument("--export", metavar="EXPORT_DIR", help="check mode: export folder (from export.ps1)")
    a = ap.parse_args()
    if a.check:
        problems = check(a.check, a.export)
        for p in problems:
            print("CHECK FAIL:", p)
        print("check: %s" % ("OK" if not problems else "%d problem(s)" % len(problems)))
        sys.exit(1 if problems else 0)
    if not a.table:
        ap.error("table is required")
    generate(a)


if __name__ == "__main__":
    main()
